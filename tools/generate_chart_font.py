#!/usr/bin/env python3
"""Bake Noto Sans SC into 4-bit glyphs; firmware never uses host fonts."""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser()
parser.add_argument("font", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
chinese = "天线转角慢速动设备模拟静置校准保持水平等待信号未发现错误"
glyphs = []
data = bytearray()
for size in (14, 20, 28):
    font = ImageFont.truetype(str(args.font), size)
    font.set_variation_by_name("Medium")
    chars = "0123456789+-" if size == 28 else "".join(chr(c) for c in range(32, 127)) + "°" + chinese
    for char in sorted(set(chars), key=ord):
        width = 18 if size == 28 else round(font.getlength(char))
        width = max(width, 1)
        image = Image.new("L", (width, size + 3))
        draw = ImageDraw.Draw(image)
        ink_width = font.getlength(char)
        draw.text(((width - ink_width) / 2, -2), char, font=font, fill=255)
        pixels = list(image.getdata())
        offset = len(data)
        for p in range(0, len(pixels), 2):
            data.append((pixels[p] >> 4) << 4 | (pixels[p + 1] >> 4 if p + 1 < len(pixels) else 0))
        glyphs.append((ord(char), offset, size, width, size + 3))
lines = ["/* Generated by tools/generate_chart_font.py; Noto Sans SC, SIL OFL 1.1. */",
         "#pragma once", "#include <stdint.h>",
         "typedef struct { uint32_t code, offset; uint8_t size, width, height; } chart_glyph_t;",
         "static const chart_glyph_t chart_glyphs[] = {"]
lines += ["    {%d, %d, %d, %d, %d}," % g for g in glyphs]
lines += ["};", "static const uint8_t chart_font_data[] = {"]
lines += ["    " + ",".join("0x%02x" % b for b in data[p:p + 24]) + "," for p in range(0, len(data), 24)]
lines += ["};", ""]
args.output.write_text("\n".join(lines))
print(f"{len(glyphs)} glyphs, {len(data)} bytes")
