#!/usr/bin/env python3
"""Bake Noto Sans SC into 4-bit glyphs; firmware never uses host fonts.

The box comes from the font's own ascent/descent, then every size is trimmed to
the rows its glyphs actually ink, so descenders and the underscore survive while
no size wastes blank rows. A blank non-space glyph aborts the build. `top` is the
first inked row relative to the ascent baseline box, so the renderer can stack
sizes on a shared baseline.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser()
parser.add_argument("font", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
chinese = "天线转角慢速动设备模拟静置校准保持水平等待信号未发现错误"
# 18/24 carry Latin+Chinese; 12/14 are auxiliary; 24 is digits-only for the RSSI readout.
sizes = (12, 14, 18, 24)
digits_only = {24}
glyphs = []
data = bytearray()
for size in sizes:
    font = ImageFont.truetype(str(args.font), size)
    font.set_variation_by_name("Medium")
    chars = ("0123456789+-" if size in digits_only
             else "".join(chr(c) for c in range(32, 127)) + "°" + chinese)
    ascent, descent = font.getmetrics()
    full_height = ascent + descent
    # Monospace the digit box so a changing reading never shifts its neighbours.
    digit_width = max(round(font.getlength(c)) for c in "0123456789")
    rendered = []
    for char in sorted(set(chars), key=ord):
        width = digit_width if char in "0123456789+-" else max(round(font.getlength(char)), 1)
        image = Image.new("L", (width, full_height))
        draw = ImageDraw.Draw(image)
        ink_width = font.getlength(char)
        draw.text(((width - ink_width) / 2, 0), char, font=font, fill=255, anchor="la")
        pixels = list(image.get_flattened_data())
        if char != " " and not any(pixels):
            raise SystemExit(f"glyph {char!r} at {size}px baked blank; box clips its ink")
        rendered.append((char, width, pixels))
    # Trim uniformly per size: keep a shared baseline, drop rows nothing inks.
    inked = [y for _c, w, px in rendered for y in range(full_height)
             if any(px[y * w:(y + 1) * w])]
    top, bottom = min(inked), max(inked)
    height = bottom - top + 1
    for char, width, pixels in rendered:
        cropped = pixels[top * width:(bottom + 1) * width]
        offset = len(data)
        for p in range(0, len(cropped), 2):
            data.append((cropped[p] >> 4) << 4 |
                        (cropped[p + 1] >> 4 if p + 1 < len(cropped) else 0))
        glyphs.append((ord(char), offset, size, width, height, top))
lines = ["/* Generated by tools/generate_chart_font.py; Noto Sans SC, SIL OFL 1.1. */",
         "#pragma once", "#include <stdint.h>",
         "typedef struct { uint32_t code, offset; uint8_t size, width, height, top; } chart_glyph_t;",
         "static const chart_glyph_t chart_glyphs[] = {"]
lines += ["    {%d, %d, %d, %d, %d, %d}," % g for g in glyphs]
lines += ["};", "static const uint8_t chart_font_data[] = {"]
lines += ["    " + ",".join("0x%02x" % b for b in data[p:p + 24]) + "," for p in range(0, len(data), 24)]
lines += ["};", ""]
args.output.write_text("\n".join(lines))
print(f"{len(glyphs)} glyphs, {len(data)} bytes")
